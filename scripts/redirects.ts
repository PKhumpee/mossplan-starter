// Generates Cloudflare _redirects in the static output from snapshot.redirects (CONTRACTS §7, §8),
// and writes src/server/redirects-data.ts for the Worker runtime (CONTRACTS §3, D30).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { StaticRedirect } from '../src/shared/redirects';
import { SnapshotSchema, type Snapshot } from '../src/shared/snapshot';

export function getSnapshot(): Snapshot {
  const envPath = process.env.SNAPSHOT_PATH;
  const snapshotPath = envPath
    ? resolve(process.cwd(), envPath)
    : resolve(process.cwd(), '.cache/content-snapshot.json');
  const fixturePath = resolve(process.cwd(), 'fixtures/content-snapshot.sample.json');

  const file = existsSync(snapshotPath) ? snapshotPath : fixturePath;
  const raw = readFileSync(file, 'utf8');
  return SnapshotSchema.parse(JSON.parse(raw));
}

export function generateRedirects(redirects: Snapshot['redirects']): string {
  const lines: string[] = [
    '# Generated by scripts/redirects.ts from content snapshot (single-hop 301s)',
    '/sitemap.xml /sitemap-index.xml 301',
  ];

  for (const r of redirects) {
    const from = r.from.startsWith('/') ? r.from : `/${r.from}`;
    const to = r.to.startsWith('/') ? r.to : `/${r.to}`;

    // Base exact redirect
    lines.push(`${from} ${to} 301`);

    // Category, tag, and author listings also cover their page/<n>/ URLs with a splat wildcard (CONTRACTS §3)
    if (from.startsWith('/category/') || from.startsWith('/tag/') || from.startsWith('/authors/')) {
      const fromPrefix = from.replace(/\/$/, '');
      const toPrefix = to.replace(/\/$/, '');
      lines.push(`${fromPrefix}/page/* ${toPrefix}/page/:splat 301`);
    }
  }

  return lines.join('\n') + '\n';
}

export function generateRedirectsData(redirects: Snapshot['redirects']): StaticRedirect[] {
  const list: StaticRedirect[] = [{ from: '/sitemap.xml', to: '/sitemap-index.xml' }];

  for (const r of redirects) {
    const from = r.from.startsWith('/') ? r.from : `/${r.from}`;
    const to = r.to.startsWith('/') ? r.to : `/${r.to}`;
    list.push({ from, to });
  }

  return list;
}

/** Drop redirects whose source URL is now owned by a live article (the article wins). */
export function liveRedirects(snapshot: Snapshot): Snapshot['redirects'] {
  const live = new Set(snapshot.articles.map((a) => `/articles/${a.slug}/`));
  return snapshot.redirects.filter(
    (r) => !live.has(r.from.startsWith('/') ? r.from : `/${r.from}`),
  );
}

export function writeRedirects(snapshot: Snapshot): void {
  const redirects = [
    ...liveRedirects(snapshot),
    ...snapshot.articles.map((article) => ({
      from: `/articles/${article.slug}/`,
      to: `/${article.slug}/`,
    })),
  ];
  const content = generateRedirects(redirects);
  const dataList = generateRedirectsData(redirects);

  // Write to dist/client/_redirects (Cloudflare static assets output)
  const distDir = resolve(process.cwd(), 'dist/client');
  if (existsSync(distDir)) {
    writeFileSync(resolve(distDir, '_redirects'), content, 'utf8');
    console.log(`[redirects] wrote ${snapshot.redirects.length} rules to dist/client/_redirects`);
  }

  // Also write to public/_redirects for development and static assets fallback
  const publicDir = resolve(process.cwd(), 'public');
  if (existsSync(publicDir)) {
    writeFileSync(resolve(publicDir, '_redirects'), content, 'utf8');
  }

  // Write to src/server/redirects-data.ts for Worker runtime
  const serverDataPath = resolve(process.cwd(), 'src/server/redirects-data.ts');
  const code = `// Generated by scripts/redirects.ts from content snapshot (single-hop 301s)
import type { StaticRedirect } from '../shared/redirects';

export const staticRedirects: StaticRedirect[] = ${JSON.stringify(dataList, null, 2)};
`;
  writeFileSync(serverDataPath, code, 'utf8');
}

function main(): void {
  const snapshot = getSnapshot();
  writeRedirects(snapshot);
}

const isMain =
  process.argv[1] &&
  (import.meta.url === pathToFileURL(resolve(process.argv[1])).href ||
    process.argv[1].endsWith('redirects.ts'));

if (isMain) {
  main();
}
